#!/usr/bin/env python3
"""Create versioned map-dependent profiles; preserve all prior versions."""
from pathlib import Path
import sys
import yaml
from lxml import etree as E
from build_v87_highway_gis_compaction import ROOT,OUTPUT,REMAPPED,EDIT_LANES
from build_v86_highway_lane_end_lc import sha256,tags
REPO=ROOT.parent
sys.path.insert(0,str(REPO/'base_ws/src/planning_addons/competition_route_requester/src'))
from competition_route_requester.geometry import Geometry,project

def remap(value):
    if isinstance(value,int):return REMAPPED.get(value,value)
    if isinstance(value,list):
        out=[]
        for item in value:
            mapped=remap(item)
            if not out or mapped!=out[-1]:out.append(mapped)
        return out
    if isinstance(value,dict):
        out={}
        for key,item in value.items():
            new_key=str(REMAPPED.get(int(key),int(key))) if isinstance(key,str) and key.isdigit() else key
            mapped=remap(item)
            if new_key in out:assert out[new_key]==mapped,(new_key,out[new_key],mapped)
            out[new_key]=mapped
        return out
    return value

def save(path,data):
    assert not path.exists(),path
    path.write_text('# K-City v87; generated by prepare_v87_profiles.py.\n'+yaml.safe_dump(data,allow_unicode=True,sort_keys=False))

def main():
    conf=REPO/'base_ws/src/planning_addons/competition_route_requester/config'
    route=remap(yaml.safe_load((conf/'kcity_v86_competition_route.yaml').read_text()))
    route['map'].update(version=87,file=str(OUTPUT.relative_to(REPO)),sha256=sha256(OUTPUT))
    geom=Geometry(str(REPO),route)
    for pose in route['poses'].values():
        if pose['lanelet_id'] in EDIT_LANES:
            pose['lanelet_s_m']=round(project(geom.lanes[pose['lanelet_id']][0],pose['x'],pose['y'])[1],6)
    save(conf/'kcity_v87_competition_route.yaml',route)
    cfg=yaml.safe_load((conf/'competition_route_requester_v86.param.yaml').read_text())
    cfg['route_definition_file']='kcity_v87_competition_route.yaml'
    save(conf/'competition_route_requester_v87.param.yaml',cfg)
    mdir=REPO/'base_ws/src/planning_addons/ajounice_planning_integration/config'
    mission=remap(yaml.safe_load((mdir/'mission_planner_kcity_v85.yaml').read_text()))
    mission['route_section_excluded_lanelet_ids']=list(dict.fromkeys(mission['route_section_excluded_lanelet_ids']))
    save(mdir/'mission_planner_kcity_v87.yaml',mission)
    caps=yaml.safe_load((ROOT/'lanelet_map/lanelet_speed_limits.yaml').read_text())
    limits={}
    for key,value in caps['lanelet_speed_limits'].items():
        key=str(REMAPPED.get(int(key),int(key)));limits[key]=min(limits.get(key,value),value)
    caps.update(map_file=str(OUTPUT.relative_to(REPO)),map_sha256=sha256(OUTPUT),lanelet_speed_limits=limits)
    save(ROOT/'lanelet_map/lanelet_speed_limits_v87.yaml',caps)
    rule_dir=REPO/'base_ws/src/competition/competition_rule_monitor/config'
    rules=yaml.safe_load((rule_dir/'kcity_v85_rules.yaml').read_text())
    count=sum(tags(r).get('subtype')=='road' and float(tags(r).get('speed_limit',0))>60 for r in E.parse(str(OUTPUT)).findall('relation'))
    rules.update(map_version=87,map_sha256=sha256(OUTPUT));rules['high_speed_exception']['expected_lanelet_count']=count
    save(rule_dir/'kcity_v87_rules.yaml',rules)
    print('Created v87 route, requester, mission, speed caps, and rule-monitor profiles; high-speed lanes:',count)
if __name__=='__main__':main()
